export type TranslationKey = keyof typeof translations.en;

export function getStatusKey(code: number | null, isGenerating: boolean): TranslationKey {
  if (isGenerating && code !== 1 && code !== 2 && code !== 5) {
    return "statusGenerating";
  }
  switch (code) {
    case 0:
      return "statusStandby";
    case 1:
      return "statusOffline";
    case 2:
      return "statusFault";
    case 3:
      return "statusStandby";
    case 4:
      return "statusWarning";
    case 5:
      return "statusError";
    case 6:
      return "statusProtocolError";
    default:
      return "statusUnknown";
  }
}

export function getStatusColor(
  code: number | null,
  isGenerating: boolean,
): "green" | "yellow" | "red" | "gray" {
  if (isGenerating) return "green";
  if (code === 1) return "gray";
  if (code === 2 || code === 5 || code === 6) return "red";
  if (code === 3 || code === 4) return "yellow";
  if (code === 0) return "yellow";
  return "gray";
}
